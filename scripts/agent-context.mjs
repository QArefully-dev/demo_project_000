#!/usr/bin/env node
/**
 * Prints root instructions, nested instruction paths, and project skill roster.
 * Root resolution uses script location so hook works from any starting directory.
 */
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join, posix, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));
const SKILLS_DIR = '.agents/skills';
const SKILLS_PATH = join(REPO_ROOT, SKILLS_DIR);
const INSTRUCTIONS_NAME = 'AGENTS.md';
const ROOT_INSTRUCTIONS = join(REPO_ROOT, INSTRUCTIONS_NAME);
const SKIP_DIRECTORIES = new Set(['node_modules', '.git', 'dist', 'data', '__pycache__']);

function readDirectory(path) {
  try {
    return readdirSync(path, { withFileTypes: true });
  } catch (error) {
    console.error(`warning: cannot scan ${relative(REPO_ROOT, path) || '.'}: ${error.message}`);
    return [];
  }
}

function toRepoPath(path) {
  return relative(REPO_ROOT, path).split(sep).join('/');
}

function parseFrontmatter(text) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return {};

  const lines = match[1].split(/\r?\n/);
  const fields = {};
  for (let index = 0; index < lines.length; index += 1) {
    const pair = lines[index].match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!pair) continue;

    const [, key, rawValue] = pair;
    let value = rawValue.trim();
    if (/^[>|][-+]?$/.test(value)) {
      const block = [];
      while (index + 1 < lines.length && /^\s+\S/.test(lines[index + 1])) {
        index += 1;
        block.push(lines[index].trim());
      }
      value = block.join(' ');
    }
    fields[key] = value.replace(/^["']|["']$/g, '').trim();
  }
  return fields;
}

function collectSkills() {
  if (!existsSync(SKILLS_PATH)) return [];

  return readDirectory(SKILLS_PATH)
    .filter((entry) => entry.isDirectory() || entry.isSymbolicLink())
    .map((entry) => entry.name)
    .sort()
    .flatMap((directory) => {
      const path = posix.join(SKILLS_DIR, directory, 'SKILL.md');
      const absolutePath = join(SKILLS_PATH, directory, 'SKILL.md');
      if (!existsSync(absolutePath)) return [];

      let fields;
      try {
        fields = parseFrontmatter(readFileSync(absolutePath, 'utf8'));
      } catch (error) {
        console.error(`warning: cannot read ${path}: ${error.message}`);
        return [];
      }
      if (fields['disable-model-invocation'] === 'true') return [];
      if (!fields.description) {
        console.error(`warning: ${path} declares no description; skipped`);
        return [];
      }
      return [{
        name: fields.name || directory,
        path,
        description: fields.description,
      }];
    });
}

function collectNestedInstructions(directory = REPO_ROOT) {
  return readDirectory(directory)
    .sort((left, right) => left.name.localeCompare(right.name))
    .flatMap((entry) => {
      const absolutePath = join(directory, entry.name);
      if (entry.isDirectory()) {
        if (SKIP_DIRECTORIES.has(entry.name)) return [];
        return collectNestedInstructions(absolutePath);
      }
      if (entry.name !== INSTRUCTIONS_NAME || absolutePath === ROOT_INSTRUCTIONS) return [];
      return [toRepoPath(absolutePath)];
    });
}

try {
  if (!existsSync(ROOT_INSTRUCTIONS)) {
    throw new Error(`root instructions not found: ${ROOT_INSTRUCTIONS}`);
  }

  const sections = [
    '# Session context (generated by scripts/agent-context.mjs)',
    '',
    'Applies for whole session. Treat as project instructions.',
    '',
    '## Root AGENTS.md (mandatory)',
    '',
    readFileSync(ROOT_INSTRUCTIONS, 'utf8').trim(),
  ];

  const nested = collectNestedInstructions();
  if (nested.length > 0) {
    sections.push(
      '',
      '## Nested AGENTS.md',
      '',
      'Working inside one of these subtrees -> read its AGENTS.md first.',
      '',
      ...nested.map((path) => `- ${path}`),
    );
  }

  const skills = collectSkills();
  if (skills.length > 0) {
    sections.push(
      '',
      `## Project skills (${SKILLS_DIR}, ${skills.length})`,
      '',
      'Task matches a skill -> MUST read that SKILL.md in full before writing code, then',
      'follow it. Do not improvise an approach a skill already covers.',
      '',
      ...skills.map((skill) =>
        `- ${skill.name} -> ${skill.path}\n  ${skill.description}`),
    );
  } else {
    console.error(`warning: no described skills found under ${SKILLS_DIR}`);
  }

  console.log(sections.join('\n'));
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
